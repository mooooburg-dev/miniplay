export function gameJsonLd(id: GameType) {
  const seo = GAME_SEO[id]
  const game = GAMES.find((g) => g.id === id)!
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: '미니게임 모음', item: SITE_URL },
          { '@type': 'ListItem', position: 2, name: game.name, item: gameUrl(id) },
        ],
      },
      {
        '@type': 'WebApplication',
        name: game.name,
        url: gameUrl(id),
        description: seo.description,
        image: gameOgImage(id),
        applicationCategory: 'GameApplication',
        operatingSystem: 'Web',
        inLanguage: 'ko',
        isAccessibleForFree: true,
        offers: { '@type': 'Offer', price: '0', priceCurrency: 'KRW' },
      },
      {
        '@type': 'FAQPage',
        mainEntity: seo.faq.map(({ q, a }) => ({
          '@type': 'Question',
          name: q,
          acceptedAnswer: { '@type': 'Answer', text: a },
        })),
      },
    ],
  }
}
